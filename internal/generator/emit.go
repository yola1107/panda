package generator

import (
	"strconv"

	routev1 "github.com/yola1107/panda/api/panda/route/v1"

	"google.golang.org/protobuf/compiler/protogen"
)

const module = "github.com/yola1107/panda/"

func ident(path, name string) protogen.GoIdent {
	return protogen.GoIdent{GoImportPath: protogen.GoImportPath(path), GoName: name}
}

func generateFile(plugin *protogen.Plugin, file *protogen.File, services []*service) {
	g := plugin.NewGeneratedFile(file.GeneratedFilenamePrefix+"_panda.pb.go", file.GoImportPath)
	g.P("// Code generated by protoc-gen-go-panda. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P("package ", file.GoPackageName)

	for _, s := range services {
		generateHandler(g, s)
		generateRegistration(g, s)
		generatePandaClient(g, s)

		for _, push := range s.pushes {
			generatePush(g, s, push)
		}
	}
}

func generateHandler(g *protogen.GeneratedFile, s *service) {
	name := s.proto.GoName
	g.P("// ", name, "Service 是逻辑服务的全限定名。")
	g.P("const ", name, "Service = ", strconv.Quote(string(s.proto.Desc.FullName())))

	for _, m := range s.methods {
		g.P("const ", name, m.proto.GoName, "Route uint32 = ", m.route.Number)
	}

	for _, p := range s.pushes {
		g.P("const ", name, "Push", p.message.GoIdent.GoName, "Route uint32 = ", p.route.Number)
	}

	g.P("// ", name, "Handler 由业务实现；登录返回独立的可信用户身份。")
	g.P("type ", name, "Handler interface {")

	for _, m := range s.methods {
		if m.route.Kind == routev1.Kind_KIND_NOTIFY {
			g.P(m.proto.GoName, "(", ident("context", "Context"), ", *", m.proto.Input.GoIdent, ") error")
			continue
		}

		identity := ""
		if m.route.Kind == routev1.Kind_KIND_LOGIN {
			identity = ", string"
		}

		g.P(
			m.proto.GoName, "(", ident("context", "Context"), ", *", m.proto.Input.GoIdent, ") ",
			"(*", m.proto.Output.GoIdent, identity, ", error)",
		)
	}

	g.P("}")
}

func generateRegistration(g *protogen.GeneratedFile, s *service) {
	name := s.proto.GoName
	g.P("// Register", name, " 注册声明的路由；默认支持 Protobuf 和 JSON。")
	g.P("func Register", name, "(n *", ident(module+"node", "Node"), ", h ", name, "Handler, codecs ...string) error {")
	g.P("if len(codecs) == 0 { codecs = []string{\"proto\", \"json\"} }")
	g.P("return n.Register(", name, "Service, codecs,")

	for _, m := range s.methods {
		generateRoute(g, name, m)
	}

	for _, p := range s.pushes {
		g.P(
			ident(module+"node", "Route"), "{Number: ", p.route.Number,
			", Type: ", ident(module+"protocol", "Push"),
			", New: func() ", ident("google.golang.org/protobuf/proto", "Message"),
			" { return new(", p.message.GoIdent, ") }},",
		)
	}

	g.P(")")
	g.P("}")
}

func generateRoute(g *protogen.GeneratedFile, name string, m method) {
	typ := "Request"
	if m.route.Kind == routev1.Kind_KIND_NOTIFY {
		typ = "Notify"
	}

	g.P(
		ident(module+"node", "Route"), "{Number: ", name, m.proto.GoName, "Route",
		", Type: ", ident(module+"protocol", typ),
		", Login: ", m.route.Kind == routev1.Kind_KIND_LOGIN, ",",
	)
	g.P("New: func() ", ident("google.golang.org/protobuf/proto", "Message"), " { return new(", m.proto.Input.GoIdent, ") },")
	g.P(
		"Handle: func(ctx ", ident("context", "Context"),
		", message ", ident("google.golang.org/protobuf/proto", "Message"),
		") (", ident(module+"node", "Result"), ", error) {",
	)
	g.P("request, ok := message.(*", m.proto.Input.GoIdent, ")")
	g.P(
		"if !ok { return ", ident(module+"node", "Result"), "{}, ",
		ident("github.com/go-kratos/kratos/v3/errors", "BadRequest"),
		"(\"INVALID_PAYLOAD\", \"unexpected message type\") }",
	)

	switch m.route.Kind {
	case routev1.Kind_KIND_NOTIFY:
		g.P("return ", ident(module+"node", "Result"), "{}, h.", m.proto.GoName, "(ctx, request)")
	case routev1.Kind_KIND_LOGIN:
		g.P("reply, user, err := h.", m.proto.GoName, "(ctx, request)")
		g.P("return ", ident(module+"node", "Result"), "{Message: reply, UserID: user}, err")
	case routev1.Kind_KIND_REQUEST:
		g.P("reply, err := h.", m.proto.GoName, "(ctx, request)")
		g.P("return ", ident(module+"node", "Result"), "{Message: reply}, err")
	case routev1.Kind_KIND_UNSPECIFIED:
	}

	g.P("}},")
}

func generatePandaClient(g *protogen.GeneratedFile, s *service) {
	name := s.proto.GoName
	g.P("// ", name, "PandaClient 提供类型化请求与通知。")
	g.P("type ", name, "PandaClient struct { transport *", ident(module+"client", "Client"), " }")
	g.P(
		"func New", name, "PandaClient(c *", ident(module+"client", "Client"), ") *", name, "PandaClient ",
		"{ return &", name, "PandaClient{transport:c} }",
	)

	for _, m := range s.methods {
		if m.route.Kind == routev1.Kind_KIND_NOTIFY {
			g.P(
				"func (c *", name, "PandaClient) ", m.proto.GoName,
				"(ctx ", ident("context", "Context"), ", request *", m.proto.Input.GoIdent, ") error {",
			)
			g.P("return c.transport.Notify(ctx, ", name, m.proto.GoName, "Route, request)")
		} else {
			g.P(
				"func (c *", name, "PandaClient) ", m.proto.GoName,
				"(ctx ", ident("context", "Context"), ", request *", m.proto.Input.GoIdent,
				") (*", m.proto.Output.GoIdent, ", error) {",
			)
			g.P("reply := new(", m.proto.Output.GoIdent, ")")
			g.P("if err := c.transport.Request(ctx, ", name, m.proto.GoName, "Route, request, reply); err != nil { return nil, err }")
			g.P("return reply, nil")
		}

		g.P("}")
	}
}

func generatePush(g *protogen.GeneratedFile, s *service, p push) {
	name := s.proto.GoName
	message := p.message.GoIdent.GoName
	g.P("// On", message, " 按入口 Codec 解码后调用类型化回调。")
	g.P(
		"func (c *", name, "PandaClient) On", message,
		"(callback func(", ident("context", "Context"), ", *", p.message.GoIdent, ") error) {",
	)
	g.P("c.transport.OnPush(", name, "Push", message, "Route, func(ctx ", ident("context", "Context"), ", payload []byte) error {")
	g.P("message := new(", p.message.GoIdent, ")")
	g.P("if err := c.transport.Decode(payload, message); err != nil { return err }")
	g.P("return callback(ctx, message)")
	g.P("}) }")
	g.P("// Push", name, message, " 按目标会话下发类型化消息。")
	g.P(
		"func Push", name, message, "(ctx ", ident("context", "Context"),
		", n *", ident(module+"node", "Node"),
		", target ", ident(module+"session", "Session"),
		", message *", p.message.GoIdent, ") error {",
	)
	g.P("return n.Push(ctx, target, ", name, "Push", message, "Route, message)")
	g.P("}")
}
